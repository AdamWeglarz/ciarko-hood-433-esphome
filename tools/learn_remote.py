#!/usr/bin/env python3
"""Learn the hood remote from the ESP's own receiver and generate hood-codes.yaml.

The firmware (esphome/ciarko-hood.yaml) decodes frames on the ESP and logs one
line per valid frame:

    HOOD code=101000010000100100011000100000111010 m1=752 s1=255 m0=262 s0=762 sync=1645

This script groups those frames into key presses, finds the toggle bit, maps
each distinct key to a name and writes an ESPHome package with the codes and
the measured timing.

Live (press every key 2-3 times, in the order given by --keys, then Ctrl+C):

    esphome logs esphome/ciarko-hood.yaml | \\
        python3 tools/learn_remote.py --keys "Light,Fan +,Fan -,Left,Right,Timer" \\
        --hold "Timer:70" -o esphome/hood-codes.yaml

From a saved log:

    python3 tools/learn_remote.py esp.log --keys "Light" -o esphome/hood-codes.yaml
"""
import argparse
import re
import statistics
import sys
from collections import Counter

HOOD = re.compile(
    r'\[(\d+):(\d+):(\d+)\.(\d+)\].*HOOD code=([01]+) '
    r'm1=(\d+) s1=(\d+) m0=(\d+) s0=(\d+) sync=(\d+)')
PRESS_GAP = 0.4        # s; frames closer than this belong to one key press
SYNC_SPACE = 4680      # us; not measurable with idle 4ms, value from RFLink + offset

ICONS = {'light': 'mdi:lightbulb', 'fan +': 'mdi:fan-plus', 'fan -': 'mdi:fan-minus',
         'left': 'mdi:chevron-left', 'right': 'mdi:chevron-right', 'timer': 'mdi:timer-outline'}


def read_frames(stream):
    frames = []
    try:
        for line in stream:
            m = HOOD.search(line)
            if not m:
                continue
            h, mi, s, ms = (int(v) for v in m.groups()[:4])
            t = h * 3600 + mi * 60 + s + int(ms) / 10 ** len(m.group(4))
            code = m.group(5)
            timing = tuple(int(v) for v in m.groups()[5:])
            frames.append((t, code, timing))
            print(f'  frame {code} {timing}', file=sys.stderr)
    except KeyboardInterrupt:
        pass
    return frames


def group_presses(frames, length):
    """One code per key press: most common full-length code within a burst."""
    presses, burst, last = [], [], None
    for t, code, _ in frames:
        if last is not None and t - last > PRESS_GAP and burst:
            presses.append(Counter(burst).most_common(1)[0][0])
            burst = []
        if len(code) == length:
            burst.append(code)
        last = t
    if burst:
        presses.append(Counter(burst).most_common(1)[0][0])
    return presses


def find_toggle(presses, default):
    """Toggle bit = position where consecutive presses of one key differ by 1 bit."""
    pos = Counter()
    for a, b in zip(presses, presses[1:]):
        diff = [i for i in range(len(a)) if a[i] != b[i]]
        if len(diff) == 1:
            pos[diff[0]] += 1
    return pos.most_common(1)[0][0] if pos else default


def with_bit(code, i, v):
    return code[:i] + v + code[i + 1:]


def render(keys, timing, holds):
    """keys: list of (name, code_on, code_off); timing: dict; holds: {name: frames}."""
    out = [
        '# Generated by tools/learn_remote.py - codes and timing of one remote.',
        '# Timing = what the ESP receiver measured from the original remote (us).',
        'substitutions:',
    ]
    out += [f'  {k}: "{v}"' for k, v in timing.items()]
    out += ['', 'button:']
    buttons = [(n, on, off, 6) for n, on, off in keys]
    for n, on, off in keys:
        if n in holds:
            buttons.append((f'{n} (long press)', on, off, holds[n]))
    for name, on, off, times in buttons:
        base = name.replace(' (long press)', '').lower()
        icon = ICONS.get(base, 'mdi:remote')
        if name.endswith('(long press)'):
            icon = 'mdi:timer-cog-outline' if base == 'timer' else icon
        out += [
            '  - platform: template',
            f'    name: "{name}"',
            f'    icon: {icon}',
            '    on_press:',
            '      - script.execute:',
            '          id: hood_send',
            f"          code_on: '{on}'",
            f"          code_off: '{off}'",
            f'          times: {times}',
            '',
        ]
    return '\n'.join(out).rstrip() + '\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('log', nargs='?', help='ESPHome log file (default: stdin)')
    ap.add_argument('--keys', default='Light,Fan +,Fan -,Left,Right,Timer',
                    help='names in the order the keys were first pressed')
    ap.add_argument('--hold', action='append', default=[],
                    help='NAME:FRAMES adds a long-press button, e.g. "Timer:70"')
    ap.add_argument('--toggle-bit', type=int, default=33,
                    help='1-based toggle bit position if it cannot be detected (default 33)')
    ap.add_argument('-o', '--output', help='write YAML here (default: stdout)')
    args = ap.parse_args()

    stream = open(args.log) if args.log else sys.stdin
    frames = read_frames(stream)
    if not frames:
        sys.exit('no HOOD frames found - is remote_receiver on_raw in the firmware?')

    length = Counter(len(c) for _, c, _ in frames).most_common(1)[0][0]
    presses = group_presses(frames, length)
    toggle = find_toggle(presses, args.toggle_bit - 1)

    names = [n.strip() for n in args.keys.split(',') if n.strip()]
    keys, seen = [], {}
    for code in presses:
        base = with_bit(code, toggle, '0')
        if base in seen:
            continue
        seen[base] = len(keys)
        name = names[len(keys)] if len(keys) < len(names) else f'Key {len(keys) + 1}'
        keys.append((name, with_bit(code, toggle, '1'), base))

    full = [tm for _, c, tm in frames if len(c) == length and tm[4] < 2000]
    med = [int(round(statistics.median(v[i] for v in full), -1)) for i in range(5)]
    timing = {'mark_one': med[0], 'space_one': med[1], 'mark_zero': med[2],
              'space_zero': med[3], 'sync_mark': med[4], 'sync_space': SYNC_SPACE}
    holds = {}
    for h in args.hold:
        n, _, f = h.rpartition(':')
        holds[n] = int(f)

    print(f'\n{len(frames)} frames, {len(presses)} presses, {length} bits, '
          f'toggle bit {toggle + 1}', file=sys.stderr)
    for n, on, off in keys:
        print(f'  {n:12s} {off} / {on}', file=sys.stderr)
    print('  timing ' + ' '.join(f'{k}={v}' for k, v in timing.items()), file=sys.stderr)

    yaml = render(keys, timing, holds)
    if args.output:
        open(args.output, 'w').write(yaml)
        print(f'written {args.output}', file=sys.stderr)
    else:
        print(yaml)


if __name__ == '__main__':
    main()
